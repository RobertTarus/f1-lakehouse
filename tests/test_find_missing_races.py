def test_get_event_slugs_cold_start_table_not_found(
    monkeypatch,
):
    """
    A missing Iceberg table is a valid cold-start state.

    Discovery should interpret TABLE_NOT_FOUND as an empty
    dataset rather than crashing the DAG.
    """

    monkeypatch.setattr(
        find_missing_races,
        "TrinoUserError",
        FakeTrinoUserError,
    )

    install_fake_connection(
        monkeypatch,
        exception=FakeTrinoUserError(
            "TABLE_NOT_FOUND"
        ),
    )

    result = (
        find_missing_races.get_event_slugs(
            "iceberg.bronze.laps",
            2026,
            "R",
        )
    )

    assert result == set()


