def test_get_event_drivers_groups_by_event(
    monkeypatch,
):
    """
    Driver rows should be grouped into one set per race.
    Duplicate drivers must collapse automatically.
    """

    install_fake_connection(
        monkeypatch,
        rows=[
            (
                "canadian-grand-prix",
                "HAM",
            ),
            (
                "canadian-grand-prix",
                "VER",
            ),
            (
                "canadian-grand-prix",
                "HAM",
            ),
            (
                "monaco-grand-prix",
                "LEC",
            ),
        ],
    )

    result = (
        find_missing_races.get_event_drivers(
            "iceberg.bronze.telemetry",
            2026,
            "R",
        )
    )

    assert result == {
        "canadian-grand-prix": {
            "HAM",
            "VER",
        },
        "monaco-grand-prix": {
            "LEC",
        },
    }


