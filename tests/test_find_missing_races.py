def test_get_event_slugs_returns_unique_events(
    monkeypatch,
):
    """
    Event slugs returned by Trino should be converted into
    a unique Python set.

    NULL values should be ignored.
    """

    install_fake_connection(
        monkeypatch,
        rows=[
            (
                "australian-grand-prix",
            ),
            (
                "canadian-grand-prix",
            ),
            (
                "canadian-grand-prix",
            ),
            (
                None,
            ),
        ],
    )

    result = (
        find_missing_races.get_event_slugs(
            "iceberg.bronze.laps",
            2026,
            "R",
        )
    )

    assert result == {
        "australian-grand-prix",
        "canadian-grand-prix",
    }


def test_get_event_slugs_generates_expected_query(
    monkeypatch,
):
    """
    Verify that the query contains the requested table,
    season, and session.
    """

    cursor = (
        install_fake_connection(
            monkeypatch,
            rows=[],
        )
    )

    find_missing_races.get_event_slugs(
        "iceberg.bronze.results",
        2026,
        "R",
    )

    assert (
        "iceberg.bronze.results"
        in cursor.query
    )

    assert (
        "season = 2026"
        in cursor.query
    )

    assert (
        "session_type = 'R'"
        in cursor.query
    )


