# ============================================================


def test_get_event_slugs_does_not_hide_unexpected_errors(
    monkeypatch,
):
    """
    Only known cold-start errors should be suppressed.

    Permission failures and other unexpected Trino errors
    must still fail loudly.
    """

    monkeypatch.setattr(
        find_missing_races,
        "TrinoUserError",
        FakeTrinoUserError,
    )

    install_fake_connection(
        monkeypatch,
        exception=FakeTrinoUserError(
            "PERMISSION_DENIED"
        ),
    )

    with pytest.raises(
        FakeTrinoUserError
    ):

        find_missing_races.get_event_slugs(
            "iceberg.bronze.laps",
            2026,
            "R",
        )
