class FakeTrinoUserError(Exception):
    """
    Minimal stand-in for trino.exceptions.TrinoUserError.

    The production code checks the exception's error_name
    attribute to distinguish expected cold-start conditions
    such as TABLE_NOT_FOUND and SCHEMA_NOT_FOUND from genuine
    Trino failures.
    """

    def __init__(
        self,
        error_name: str,
    ) -> None:

        super().__init__(
            error_name
        )

        self.error_name = (
            error_name
        )


class FakeCursor:
    """
    Small fake Trino cursor used by the unit tests.
    """

    def __init__(
        self,
        rows=None,
        exception=None,
    ) -> None:

        self.rows = (
            rows
            if rows is not None
            else []
        )

        self.exception = (
            exception
        )

        self.query = None

    def execute(
        self,
        query,
    ) -> None:

        self.query = (
            query
        )

        if self.exception:

            raise self.exception

    def fetchall(
        self,
    ):

        return self.rows

    def close(
        self,
    ) -> None:

        pass


class FakeConnection:
    """
    Small fake Trino connection used by the unit tests.
    """

    def __init__(
        self,
        cursor,
    ) -> None:

        self.fake_cursor = (
            cursor
        )

    def cursor(
        self,
    ):

        return self.fake_cursor

    def close(
        self,
    ) -> None:

        pass


def install_fake_connection(
    monkeypatch,
    rows=None,
    exception=None,
):
    """
    Replace the real Trino connection with a fake connection.

    Returns the fake cursor so individual tests may inspect
    the SQL generated by the production code if required.
    """

    cursor = FakeCursor(
        rows=rows,
        exception=exception,
    )

    connection = FakeConnection(
        cursor
    )

    monkeypatch.setattr(
        find_missing_races,
        "connect",
        lambda **kwargs: connection,
    )

    return cursor


